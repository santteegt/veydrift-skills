"""`vd plan` — the decision engine. Input: `Snapshot` + `Policy`. Output: exactly one
`Action` (its `kind` may be `noop`/`escalate`/`halt` — see `Action.is_onchain()`).

Ladder, first match wins, exactly as docs/SPEC.md §5.4 specifies:

```
0. KILLSWITCH present                -> HALT
1. /health not ok                    -> NO-OP, reason recorded (unless positively
                                         confirmed randomness/combat-only -- see
                                         Snapshot.combat_only_degradation, 2026-08-22)
1b. gameMaintenance.paused           -> ESCALATE (or NO-OP if escalation.on_game_paused
                                         is false) -- game reports a chain-side
                                         maintenance pause; any write would revert
2. pending tx unreconciled           -> NO-OP, reconcile first
3. mission Resolving > 60s           -> resolveFleetMission   (permissionless, free)
4. incoming hostile fleet            -> ESCALATE, no proposal (fleet-visibility.incoming)
5-9. a four-band candidate pipeline (see below) -- deadline-driven storage overflow,
     then economically-scored building, then policy-declared research/ships/defense,
     then a locked declared target's unlock-chain step, else an explicit NO-OP.
```

**Rungs 0-4 are vetoes — safety, not strategy — and are untouched by Phase 2 of the
general-strategy-engine program** (docs/SPEC.md §5.4). Rung 3 remains a known,
documented gap: the frozen `Snapshot` model (`models.py`) carries `incoming_fleets` (for
rung 4's hostile-fleet detection) but no list of the *player's own* fleet missions and
their status, so `plan_next_action` accepts `resolvable_mission_ids` as an explicit,
caller-supplied parameter (default empty) rather than deriving it from the snapshot.

**Rungs 5-9 are a generate/filter/score/select pipeline, in `candidates.py`.** Before
Phase 2, each rung both decided the action *family* and hardcoded *which entity* in one
function. `candidates.py` splits generation (one pure function per family) from
selection (a small function per rung that replays the exact same priority order the
pre-Phase-2 ladder used) — see that module's docstring for the full architecture. This
module now only:

1. Calls the four `select_*` functions in the four-band precedence order below.
2. Attaches the winning `Candidate`'s runner-ups to the returned `Action.alternatives`
   (`AlternativeNote`, capped at `policy.strategy.max_alternatives`) — informational
   only, never a `Decision` input, never re-derived by `guard.py`.

**Four bands, in order** (docs/SPEC.md §5.4):

1. **Deadline-driven** — storage overflow (`candidates.select_storage_candidate`). A
   loss-avoidance deadline, not an ROI question; keeps precedence over everything else
   via `policy.storage.hours_to_cap_trigger`, exactly as rung 5 always has.
2. **Economically scored** — `candidates.select_building_candidate`, ascending payback
   hours among *legal* candidates. **The energy-first invariant stays a hard filter, not
   a score**: a mine candidate that would push post-upgrade `required` past `produced`
   is never generated by `candidates.generate_mine_candidates`, and the energy candidate
   (`candidates.generate_energy_candidates`) is generated in its place — identical
   semantics to the pre-Phase-2 ladder, now expressed as "never generated" instead of
   "generated then discarded." (This band also carries `policy.strategy.building_priority`
   infrastructure picks, which — deliberately, per that field's own docstring — win
   outright over a scored mine/energy candidate when declared; see `candidates.
   select_building_candidate`.)
3. **Policy-declared** — research, ships, defenses
   (`candidates.select_research_candidate` / `select_shipyard_candidate`), gated on
   `candidates.economy_on_track` exactly as rung 8 always was.
4. **Unlock-chain** (Phase 4, rung `8b`) — `candidates.select_unlock_chain_candidate`.
   Reached only when bands 1-3 produced nothing at all for any target planet, so it can
   never outrank the storage-overflow deadline and can never displace a scored economic
   or policy-declared candidate — see that function's docstring for why it is a separate
   rung rather than folded into band 2's `building_priority` branch. Proposes the
   shallowest buildable prerequisite toward a locked `ship_targets`/`defense_targets`/
   `research_priority` entry, always `score=None` (an unlock step's value is entirely in
   what it eventually enables, not something this codebase computes an ROI for).

**The two invariants that matter most, both derived from planet traits, never
hardcoded** (unchanged by Phase 2 — see `candidates.py` for where the logic now lives):

1. **Energy-first.** `candidates.generate_mine_candidates` computes `required` at the
   *post-upgrade* mine level via `calc.energy_balance` and compares it to `produced`
   (preferring the API's live `PlanetSnapshot.energy.produced`). If the upgrade would
   push `required > produced`, that mine is never generated as a candidate; the cheaper
   of Solar Plant / Solar Satellite substitutes it.
2. **Build order is derived from planet traits.** `candidates._mine_priority_order`
   ranks Metal / Crystal / Deuterium mines by `base_rate * live_multiplier_bps` ("value
   density"), so a planet's deuterium multiplier changes the opener without any
   per-planet branch. `candidates._cheapest_energy_choice` ranks Solar Plant vs. Solar
   Satellite by cost-per-energy-point using only *live* costs (`Entity.cost`) and the
   live `solarSatelliteEnergy` — never a hardcoded planet id. See
   `references/strategy-playbook.md` for the full derivation and a worked numeric
   example on both planet 664 and a hot-planet fixture.
"""

from __future__ import annotations

import json
from pathlib import Path

import typer
from rich.console import Console
from rich.panel import Panel

from veydrift_agent import candidates
from veydrift_agent.models import (
    Action,
    ActionKind,
    AlternativeNote,
    PlanetSnapshot,
    Policy,
    QueueKind,
    Snapshot,
)

app = typer.Typer(no_args_is_help=True, help="Decide the next action from a snapshot + policy.")


def _target_planets(snapshot: Snapshot, policy: Policy) -> list[PlanetSnapshot]:
    """`policy.planets == []` means "all snapshot planets" (docs/SPEC.md §5.6); otherwise
    the policy's own order is the priority order the ladder walks in.
    """
    if not policy.planets:
        return list(snapshot.planets)
    by_id = {p.planet_id: p for p in snapshot.planets}
    return [by_id[planet_id] for planet_id in policy.planets if planet_id in by_id]


# --------------------------------------------------------------------------------------
# Candidate -> Action, attaching `rule` and `alternatives`. Shared by every band below.
# --------------------------------------------------------------------------------------


def _why_not(alternative: candidates.Candidate, winner: candidates.Candidate) -> str:
    """`"payback 47h vs 31h"` when both the alternative and the winner are scored,
    otherwise the alternative's own `score_basis` (e.g. `"locked: needs Shipyard 2 (have
    0)"`, `"deadline: metal 1.4h from cap"`)."""
    if alternative.score is not None and winner.score is not None:
        return f"payback {alternative.score:.1f}h vs winner's {winner.score:.1f}h"
    return alternative.score_basis


def _finalize(
    winner: candidates.Candidate,
    alternatives: list[candidates.Candidate],
    rule: str,
    policy: Policy,
) -> Action:
    notes = [
        AlternativeNote(
            family=alt.family,
            entity_name=alt.action.entity_name,
            score=alt.score,
            why_not=_why_not(alt, winner),
        )
        for alt in alternatives[: policy.strategy.max_alternatives]
    ]
    return winner.action.model_copy(update={"rule": rule, "alternatives": notes})


def _next_building_action(planet: PlanetSnapshot, snapshot: Snapshot, policy: Policy, rule: str) -> Action | None:
    """The energy-first opener for a single planet. Thin wrapper around
    `candidates.select_building_candidate` — kept as a standalone, importable function
    (rather than inlined into `plan_next_action`) because `tests/test_plan.py` calls it
    directly to isolate rung 6's building-pick logic from the rest of the ladder."""
    winner, alternatives = candidates.select_building_candidate(snapshot, policy, planet)
    if winner is None:
        return None
    return _finalize(winner, alternatives, rule, policy)


